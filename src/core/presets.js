/**
 * Flatten a DES S-box table into a lookup indexed by the 6-bit input.
 * @param {number[][]} rows
 * @returns {number[]}
 */
function desToLookup(rows) {
  return Array.from({ length: 64 }, (_, x) => rows[((x >> 4) & 2) | (x & 1)][(x >> 1) & 0xf]);
}

